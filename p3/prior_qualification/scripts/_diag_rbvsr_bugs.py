# -*- coding: utf-8 -*-
"""Quantify each of the reported rbvsr_net.py bugs on RealVSR clip 016.

Variants are generated by patching the source text in memory, so the
production file is untouched while we measure which fix moves PSNR.

  base      : rbvsr_net.py as committed
  lrelu     : + leaky ReLU after upsample1 / upsample2   (reported bug 1)
  warp      : + grid + flow  instead of flow.flip(1)      (reported bug 2)
  pad       : + propagation warp uses padding_mode='zeros' (reported bug 4)
  all       : all three
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import types

import cv2
import numpy as np
import torch

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "scripts", "rbvsr_net.py")
CKPT = os.path.join(ROOT, "weights_rbvsr", "RealBasicVSR_x4.pth")
DATA = os.environ.get("RVQ_DATA") or os.path.join(ROOT, "data", "realvsr")
CLIP = "016"


def patches(names):
    p = []
    if "lrelu" in names:
        p.append((
            "            x = self.basicvsr.upsample1(x)\n"
            "            x = self.basicvsr.upsample2(x)\n",
            "            x = F.leaky_relu(self.basicvsr.upsample1(x),"
            " negative_slope=0.1, inplace=True)\n"
            "            x = F.leaky_relu(self.basicvsr.upsample2(x),"
            " negative_slope=0.1, inplace=True)\n"))
    if "warp" in names:
        p.append(("    grid = grid + flow.flip(1)\n", "    grid = grid + flow\n"))
    if "pad" in names:
        p.append(("def _warp(x, flow):", "def _warp(x, flow, padding_mode=\"border\"):"))
        p.append(('mode="bilinear", padding_mode="border")',
                  'mode="bilinear", padding_mode=padding_mode)'))
        # propagation branches must use the flow_warp default, SPyNet keeps border
        p.append(("            feat_prop = _warp(feat_prop, flow)\n",
                  "            feat_prop = _warp(feat_prop, flow, padding_mode=\"zeros\")\n"))
    return p


def build_module(name, names):
    src = open(SRC, encoding="utf-8").read()
    for old, new in patches(names):
        if old not in src:
            raise SystemExit("patch anchor missing for %s:\n%r" % (name, old[:80]))
        src = src.replace(old, new, 1 if "def _warp" in old else -1)
    mod = types.ModuleType("rbvsr_%s" % name)
    mod.__file__ = SRC
    exec(compile(src, SRC, "exec"), mod.__dict__)
    return mod


def read_rgb(path):
    a = cv2.imread(path)
    if a is None:
        raise RuntimeError("unreadable %s" % path)
    return cv2.cvtColor(a, cv2.COLOR_BGR2RGB)


def psnr(a, b):
    mse = float(np.mean((a.astype(np.float64) - b.astype(np.float64)) ** 2))
    return 99.0 if mse <= 1e-12 else float(10.0 * np.log10(255.0 ** 2 / mse))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--variants", default="base,lrelu,warp,pad,all")
    ap.add_argument("--nframes", type=int, default=5)
    ap.add_argument("--order", default="rgb", choices=("rgb", "bgr"))
    args = ap.parse_args()

    lq_dir = os.path.join(DATA, "LQ4x", CLIP)
    gt_dir = os.path.join(DATA, "GT", CLIP)
    ids = sorted(os.path.splitext(f)[0] for f in os.listdir(lq_dir)
                 if f.lower().endswith(".png"))[:args.nframes]

    lq = np.stack([read_rgb(os.path.join(lq_dir, i + ".png")) for i in ids])
    gt = np.stack([read_rgb(os.path.join(gt_dir, i + ".png")) for i in ids])
    if args.order == "bgr":
        lq, gt = lq[..., ::-1].copy(), gt[..., ::-1].copy()
    print("clip %s frames %s..%s  LQ %s  GT %s  order=%s"
          % (CLIP, ids[0], ids[-1], lq.shape[1:3], gt.shape[1:3], args.order),
          flush=True)

    x = torch.from_numpy(lq).permute(0, 3, 1, 2).float().div_(255.0).cuda()
    g = gt.astype(np.float64)

    out = {}
    for name in args.variants.split(","):
        names = [] if name == "base" else (["lrelu", "warp", "pad"]
                                           if name == "all" else [name])
        mod = build_module(name, names)
        net, missing, unexpected = mod.load_rbvsr(CKPT, device="cuda")
        with torch.no_grad():
            y = net(x).clamp(0, 1).mul(255.0).permute(0, 2, 3, 1)
            y = y.round().byte().cpu().numpy().astype(np.float64)
        per = [psnr(y[i], g[i]) for i in range(len(ids))]
        bias = (y - g).mean(axis=(0, 1, 2))
        rec = {"psnr_mean": float(np.mean(per)),
               "psnr_per_frame": [round(v, 4) for v in per],
               "rgb_bias": [round(float(v), 2) for v in bias],
               "missing": len(missing), "unexpected": len(unexpected),
               "missing_keys": list(missing)[:6],
               "unexpected_keys": list(unexpected)[:6]}
        out[name] = rec
        print("%-6s PSNR %.4f  frames %s  bias(RGB) %s  missing %d unexpected %d"
              % (name, rec["psnr_mean"], rec["psnr_per_frame"], rec["rgb_bias"],
                 rec["missing"], rec["unexpected"]), flush=True)
        del net
        torch.cuda.empty_cache()

    dst = os.path.join(ROOT, "results", "rbvsr_diag", "bugs_%s.json" % args.order)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        json.dump({"clip": CLIP, "ids": ids, "order": args.order,
                   "variants": out}, f, indent=1)
    print("wrote", dst, flush=True)


if __name__ == "__main__":
    main()
