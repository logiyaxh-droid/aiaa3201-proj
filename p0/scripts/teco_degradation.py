"""Task 12 -- is TecoGAN's weakness on REDS explained by degradation mismatch?

The claim to test (it was an *assumption* in the earlier report): TecoGAN's official
weight was trained on LR made by TecoGAN's own **Gaussian** downsampler
(``tf_data_gaussDownby4``, sigma=1.5), while the course REDS LR is a plain
**bicubic** downsample; the mismatch, not the model, is what costs it PSNR.

Controlled comparison
---------------------
Same HR content, same 4x factor, same metrics, two LR pipelines:

  ``gauss``   : cv2.GaussianBlur(sigma=1.5) then INTER_CUBIC down/4  <- TecoGAN's own
  ``bicubic`` : cv2.INTER_CUBIC down/4                               <- the course LR

The HR source is the REDS val GT, so the comparison is against real REDS content
and both LR variants are derived from the *same* frames (no sampling difference).
Every method is run on both variants:

    bicubic / edsr / edvr      (cheap, GPU)
    tecogan                    (CPU, so it is optional via --with-tecogan)

The point is the *gap between the two columns for each method*.  If the mismatch
hypothesis holds, TecoGAN should gain much more than EDVR when moving to ``gauss``.

Important honesty notes baked into the output JSON:
  * the gauss LR here is generated by cv2 at 1/4 scale, not by TecoGAN's own TF
    graph; it matches the documented kernel (sigma=1.5, bicubic) but is not
    bit-identical to the TF implementation;
  * REDS GT is a *clean* source; the course LR is derived from the same clean GT,
    so this is still synthetic-degradation-to-synthetic-degradation, not real
    low-light footage (that is WILD.md's job).

Usage:
    /tmp/srenv/bin/python ~/p0/scripts/teco_degradation.py --out ~/p0/out/degradation
    ... --with-tecogan --clips 000 004 011
"""
