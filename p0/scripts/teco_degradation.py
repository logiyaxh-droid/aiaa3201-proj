torch.backends.cudnn.benchmark = False

sys.path.insert(0, os.path.expanduser("~/p0"))
from evalkit import metrics as M, temporal as T, data as D  # noqa: E402

B = "/data/disk1/shared/aiaa3201/project1_video_sr"
GT_ROOT = B + "/val_sharp"
CK = {
    "edsr": "/data/disk1/shared/aiaa3201/checkpoints/EDSR_baseline_x4/"
            "EDSR_Mx4_f64b16_DIV2K_official-0c287733.pth",
    "edvr": "/data/disk1/shared/aiaa3201/checkpoints/EDVR_REDS_SR_L/"
            "EDVR_L_x4_SR_REDS_official-9f5f5039.pth",
}
TECO_RUN = os.path.expanduser("~/p0/scripts/run_tecogan.py")
TF1_PY = "/tmp/tf1env/bin/python"
SIGMA = 1.5


def rd(p):
    a = cv2.imread(p)
    if a is None:
        raise RuntimeError("unreadable %s" % p)
    return cv2.cvtColor(a, cv2.COLOR_BGR2RGB)


def down_gauss(img, factor=4, sigma=SIGMA):
    """TecoGAN-style Gaussian pre-blur, then bicubic downsample (OpenCV)."""
    bl = cv2.GaussianBlur(img, (0, 0), sigma)
    h, w = img.shape[:2]
    return cv2.resize(bl, (w // factor, h // factor), interpolation=cv2.INTER_CUBIC)


def down_bicubic(img, factor=4):
    h, w = img.shape[:2]
    return cv2.resize(img, (w // factor, h // factor), interpolation=cv2.INTER_CUBIC)


class EDSR:
    def __init__(self, device="cuda"):
        from basicsr.archs.edsr_arch import EDSR as Net
        ck = torch.load(CK["edsr"], map_location="cpu", weights_only=False)["params"]
        net = Net(3, 3, 64, 16, 4)
        net.load_state_dict(ck, strict=True)
        self.net = net.to(device).eval()
        for q in self.net.parameters():
            q.requires_grad_(False)
        self.device = device

    def __call__(self, lr, bs=4):
        out = []
        for i in range(0, len(lr), bs):
            x = torch.stack([torch.from_numpy(f).permute(2, 0, 1).float().div_(255.0)
                             for f in lr[i:i + bs]]).to(self.device)
            with torch.no_grad():
                y = self.net(x)
            out.append(y.clamp_(0, 1).mul_(255).round_().byte().permute(0, 2, 3, 1)
                       .cpu().numpy())
        return np.concatenate(out, 0)


class EDVR:
    def __init__(self, device="cuda"):
        from basicsr.archs.edvr_arch import EDVR as Net
        sd = torch.load(CK["edvr"], map_location="cpu", weights_only=False)["params"]
        net = Net(num_in_ch=3, num_out_ch=3, num_feat=128, num_frame=5,
                  deformable_groups=8, num_extract_block=5, num_reconstruct_block=40,
                  center_frame_idx=2, hr_in=False, with_predeblur=False, with_tsa=True)
        net.load_state_dict(sd, strict=True)
        self.net = net.to(device).eval()
        for q in self.net.parameters():
            q.requires_grad_(False)
        self.device = device

    def clip(self, lr):
        n = len(lr)
        out = []
        for c in range(n):
            win = [max(0, min(n - 1, c + d - 2)) for d in range(5)]
            x = torch.stack([torch.from_numpy(lr[w]).permute(2, 0, 1).float().div_(255.0)
                             for w in win]).unsqueeze(0).to(self.device)
            with torch.no_grad():
                y = self.net(x)
            out.append(y[0].clamp_(0, 1).mul_(255).round_().byte()
                       .permute(1, 2, 0).cpu().numpy())
        return np.stack(out, 0)


def score(pred, gt, ids, lpips_net):
    pY = np.stack([M.luma(x) for x in pred])
    gY = np.stack([M.luma(x) for x in gt])
    row = {"psnr": float(M.psnr_mean(pY, gY)),
           "ssim": float(M.ssim_gpu(pY, gY, device="cuda").mean()),
           "lpips": lpips_net.mean(pred, np.stack(gt)), "n_frames": int(len(ids))}
    pr = T.pairs_of(ids, 0)
    d_sr = lpips_net.pair(np.stack([pred[a] for a, _ in pr]),
                          np.stack([pred[b] for _, b in pr]))
    d_gt = lpips_net.pair(np.stack([gt[a] for a, _ in pr]),
                          np.stack([gt[b] for _, b in pr]))
    row["tlp"] = float(np.abs(d_sr - d_gt).mean())
    return row


def run_tecogan(lr_list, workdir, tag):
    """Write the LR frames out and let the checked TecoGAN runner produce frames."""
    os.makedirs(workdir, exist_ok=True)
    for i, f in enumerate(lr_list):
        cv2.imwrite(os.path.join(workdir, "%08d.png" % i),
                    cv2.cvtColor(f, cv2.COLOR_RGB2BGR))
    out = os.path.join(workdir, "out")
    cmd = [TF1_PY, TECO_RUN, "--lru", workdir, "--out", out,
           "--shift", "0.375", "--tag", tag]
    print("  tecogan:", " ".join(cmd), flush=True)
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("TecoGAN failed (%d):\n%s\n%s"
                           % (r.returncode, r.stdout[-2000:], r.stderr[-2000:]))
    idx = D.index_dir(out)
    return [rd(idx[i]) for i in sorted(idx)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--clips", nargs="*", default=["000", "004", "011", "019", "022"])
    ap.add_argument("--frames", type=int, default=30)
    ap.add_argument("--with-tecogan", action="store_true")
    args = ap.parse_args()
    out_dir = os.path.abspath(os.path.expanduser(args.out))
    os.makedirs(out_dir, exist_ok=True)

    lpips_net = M.LPIPS(device="cuda", torch_home="/tmp/torch_home")
    edsr = EDSR()
    edvr = EDVR()

    res = {"sigma": SIGMA, "factor": 4, "frames_per_clip": args.frames,
           "clips": args.clips,
           "lr_pipelines": {
               "gauss": "cv2.GaussianBlur(sigma=1.5) + INTER_CUBIC /4 "
                        "(TecoGAN's documented kernel, re-implemented in cv2)",
               "bicubic": "cv2.INTER_CUBIC /4 (the course REDS LR convention)"},
           "caveat": "gauss LR here is cv2, not TecoGAN's TF graph: same kernel and "
                     "scale, not bit-identical; both LR variants come from the same "
                     "clean REDS GT, so this isolates the degradation kernel only",
           "per_clip": {}, "means": {}}
    acc = {}

    for clip in args.clips:
        t0 = time.time()
        idx = D.index_dir(os.path.join(GT_ROOT, clip))
        ids = sorted(idx)[:args.frames]
        gt = [rd(idx[i]) for i in ids]
        variant = {}
        for lr_kind, fn in (("gauss", down_gauss), ("bicubic", down_bicubic)):
            lr = [fn(g) for g in gt]
            H, W = gt[0].shape[:2]
            preds = {
                "bicubic": [cv2.resize(x, (W, H), interpolation=cv2.INTER_CUBIC)
                            for x in lr],
                "edsr": list(edsr(lr)),
                "edvr": list(edvr.clip(lr)),
            }
            if args.with_tecogan:
                wd = os.path.join(out_dir, "_teco", "%s_%s" % (clip, lr_kind))
                preds["tecogan"] = run_tecogan(lr, wd, "%s_%s" % (clip, lr_kind))
            variant[lr_kind] = {m: score(p, gt, ids, lpips_net) for m, p in preds.items()}
            for m, r in variant[lr_kind].items():
                acc.setdefault(m, {}).setdefault(lr_kind, []).append(r)
        res["per_clip"][clip] = variant
        print("%s [%4.1fs] %s" % (clip, time.time() - t0,
              "  ".join("%s: gauss %.2f / bic %.2f (d %+.2f)"
                        % (m, variant["gauss"][m]["psnr"], variant["bicubic"][m]["psnr"],
                           variant["gauss"][m]["psnr"] - variant["bicubic"][m]["psnr"])
                        for m in variant["gauss"])), flush=True)
        json.dump(res, open(os.path.join(out_dir, "degradation.json"), "w",
                            encoding="utf-8"), indent=1)

    for m, d in acc.items():
        res["means"][m] = {}
        for kind in ("gauss", "bicubic"):
            if kind not in d:
                continue
            res["means"][m][kind] = {k: float(np.mean([r[k] for r in d[kind]]))
                                     for k in ("psnr", "ssim", "lpips", "tlp")}
        if "gauss" in d and "bicubic" in d:
            res["means"][m]["delta_gauss_minus_bicubic"] = {
                k: res["means"][m]["gauss"][k] - res["means"][m]["bicubic"][k]
                for k in ("psnr", "ssim", "lpips", "tlp")}
    json.dump(res, open(os.path.join(out_dir, "degradation.json"), "w", encoding="utf-8"),
              indent=1)

    print("\n== degradation A/B (mean over %d clips x %d frames) ==" % (len(args.clips), args.frames))
    print("%-10s %19s %19s %10s" % ("method", "gauss PSNR/LPIPS", "bicubic PSNR/LPIPS", "dPSNR"))
    for m, v in res["means"].items():
        g, b = v.get("gauss"), v.get("bicubic")
        if not (g and b):
            continue
        print("%-10s %8.3f / %7.4f   %8.3f / %7.4f   %+8.3f"
              % (m, g["psnr"], g["lpips"], b["psnr"], b["lpips"],
                 v["delta_gauss_minus_bicubic"]["psnr"]))
    print("->", os.path.join(out_dir, "degradation.json"))


if __name__ == "__main__":
    main()
